export function getPlaceMedia(citySlug, placeId) {
  const key = `${citySlug}:${placeId}`;
  const hit = placeMedia[key];
  const fallback = cityFallback[citySlug] || Object.values(cityFallback)[0];
  if (!hit) return { image: fallback, gallery: [fallback] };
  const gallery = hit.gallery?.length ? hit.gallery : [hit.image];
  return { image: hit.image || fallback, gallery };
}

export function enrichPlace(citySlug, place) {
  const media = getPlaceMedia(citySlug, place.id);
  return {
    ...place,
    image: place.image || media.image,
    gallery: place.gallery || media.gallery,
  };
}
